-- ===========================================================================
-- 0011  Document templates, generated documents, and public QR card tokens
-- ---------------------------------------------------------------------------
-- The QR design deserves a note, because it is the one place where anonymous
-- visitors read from this database.
--
-- qr_tokens.card_snapshot holds a frozen copy of exactly the fields printed on
-- the physical card. The public page renders that JSON and nothing else — it
-- performs no join to students, enrollments, fees, marks or contacts. So the
-- public surface cannot leak a column that was never copied into it, even if
-- a future policy is written carelessly.
--
-- Tokens are opaque and random, never derived from a registration number, and
-- revocable so a lost card's link can be killed and reissued.
-- ===========================================================================

create table public.document_templates (
  id           uuid primary key default gen_random_uuid(),
  kind         public.document_kind not null,
  name         text not null,
  orientation  public.card_orientation not null default 'portrait',
  -- Which fields the template prints, page geometry, and layout options.
  config       jsonb not null default '{}'::jsonb,
  is_default   boolean not null default false,
  is_active    boolean not null default true,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  unique (kind, name)
);

create unique index document_templates_default_per_kind_idx
  on public.document_templates (kind) where is_default;

create trigger document_templates_touch_updated_at
  before update on public.document_templates
  for each row execute function app.touch_updated_at();

comment on column public.document_templates.config is
  'Declares which fields the card prints. Drives what is copied into a QR snapshot.';

-- --------------------------------------------------------------------------
-- qr_tokens — the public digital ID card
-- --------------------------------------------------------------------------
create table public.qr_tokens (
  id             uuid primary key default gen_random_uuid(),

  -- Opaque, high-entropy, URL-safe. Generated by the application with a CSPRNG.
  -- Never derived from the registration number or any other guessable value.
  token          text not null unique check (length(token) >= 32),

  student_id     uuid not null references public.students (id) on delete cascade,
  template_id    uuid references public.document_templates (id) on delete set null,

  -- Exactly the card's printed fields, plus school name/logo/email/office phone.
  -- Must never contain parent names, NIDs, birth certificate number, fees,
  -- marks, attendance or account data.
  card_snapshot  jsonb not null,

  issued_at      timestamptz not null default now(),
  issued_by      uuid references public.profiles (id) on delete set null,

  revoked_at     timestamptz,
  revoked_by     uuid references public.profiles (id) on delete set null,
  revoke_reason  text,
  -- Points at the token that replaced this one, for lost-card reissue history.
  replaced_by_id uuid references public.qr_tokens (id) on delete set null,

  constraint qr_tokens_revoke_needs_reason check (
    revoked_at is null or length(btrim(coalesce(revoke_reason, ''))) > 0
  )
);

-- A student holds at most one live card link at a time.
create unique index qr_tokens_single_active_idx
  on public.qr_tokens (student_id) where revoked_at is null;

create index qr_tokens_lookup_idx on public.qr_tokens (token) where revoked_at is null;

comment on table public.qr_tokens is
  'Opaque revocable tokens for the public ID-card page. The snapshot is the entire public surface.';
comment on column public.qr_tokens.card_snapshot is
  'Frozen printed-card fields only. No parent names, NIDs, fees, marks or attendance.';

-- Defence in depth: reject a snapshot that carries a key the public page must
-- never show, even if application code is changed carelessly later.
create or replace function app.enforce_qr_snapshot_safe()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  v_forbidden text[] := array[
    'father_name', 'mother_name', 'fathers_name', 'mothers_name',
    'father_nid', 'mother_nid', 'nid', 'parent_nid',
    'birth_certificate_no', 'birth_certificate',
    'fees', 'fee_status', 'marks', 'result', 'results', 'gpa', 'grade',
    'attendance', 'attendance_pct', 'password', 'auth_user_id', 'email_otp'
  ];
  v_key text;
begin
  foreach v_key in array v_forbidden loop
    if new.card_snapshot ? v_key then
      raise exception
        'qr card_snapshot may not contain the key "%" — it is not public card data',
        v_key
        using errcode = 'check_violation';
    end if;
  end loop;
  return new;
end;
$$;

create trigger qr_tokens_snapshot_safe
  before insert or update of card_snapshot on public.qr_tokens
  for each row execute function app.enforce_qr_snapshot_safe();

-- --------------------------------------------------------------------------
-- admit_card_rules — the eligibility policy per exam
-- --------------------------------------------------------------------------
-- The exact fee window and whether any override is permitted are owner
-- decisions (brief 12.2). They are stored as configuration so the rule can be
-- set per exam without a code change, and so the office cannot bypass it by
-- using a different screen.
-- --------------------------------------------------------------------------
create table public.admit_card_rules (
  id                        uuid primary key default gen_random_uuid(),
  exam_id                   uuid not null unique references public.exams (id) on delete cascade,

  -- Feedback requirement.
  require_feedback          boolean not null default true,
  feedback_campaign_id      uuid references public.feedback_campaigns (id) on delete set null,

  -- Fee requirement: monthly fees must be cleared through this month of the
  -- academic year, and the exam fee itself must be settled.
  require_fees_cleared      boolean not null default true,
  fees_cleared_through_year  integer,
  fees_cleared_through_month smallint check (
    fees_cleared_through_month is null
    or fees_cleared_through_month between 1 and 12
  ),
  require_exam_fee_paid     boolean not null default true,
  -- Outstanding amount tolerated before the card is blocked.
  allowed_outstanding       numeric(10,2) not null default 0 check (allowed_outstanding >= 0),

  -- Overrides are OFF unless the owner approves that policy. When enabled,
  -- every override is recorded in admit_card_overrides and audit_logs.
  allow_override            boolean not null default false,

  created_at                timestamptz not null default now(),
  updated_at                timestamptz not null default now(),

  constraint admit_card_rules_fee_window check (
    (fees_cleared_through_year is null) = (fees_cleared_through_month is null)
  )
);

create trigger admit_card_rules_touch_updated_at
  before update on public.admit_card_rules
  for each row execute function app.touch_updated_at();

comment on column public.admit_card_rules.allow_override is
  'Off by default. The brief permits an audited exception only if the owner approves it.';

create table public.admit_card_overrides (
  id             uuid primary key default gen_random_uuid(),
  exam_id        uuid not null references public.exams (id) on delete cascade,
  student_id     uuid not null references public.students (id) on delete cascade,
  reason         text not null check (length(btrim(reason)) > 0),
  -- The eligibility failures that were overridden, captured at the time.
  overridden_checks jsonb not null default '[]'::jsonb,
  approved_by    uuid references public.profiles (id) on delete set null,
  approved_at    timestamptz not null default now(),
  unique (exam_id, student_id)
);

comment on table public.admit_card_overrides is
  'Every exceptional admit-card issue. Separately audited; requires allow_override.';

-- --------------------------------------------------------------------------
-- generated_documents — what has actually been produced, and by whom
-- --------------------------------------------------------------------------
create table public.generated_documents (
  id            uuid primary key default gen_random_uuid(),
  kind          public.document_kind not null,
  template_id   uuid references public.document_templates (id) on delete set null,

  -- Exactly one scope is set: an individual student, a whole section, or a
  -- school-wide document.
  student_id    uuid references public.students (id) on delete cascade,
  section_id    uuid references public.sections (id) on delete cascade,
  exam_id       uuid references public.exams (id) on delete cascade,
  academic_year_id uuid references public.academic_years (id) on delete cascade,

  file_path     text,
  page_count    integer check (page_count is null or page_count > 0),
  meta          jsonb not null default '{}'::jsonb,

  generated_at  timestamptz not null default now(),
  generated_by  uuid references public.profiles (id) on delete set null
);

create index generated_documents_student_idx
  on public.generated_documents (student_id, kind, generated_at desc);

create index generated_documents_section_idx
  on public.generated_documents (section_id, kind, generated_at desc);
